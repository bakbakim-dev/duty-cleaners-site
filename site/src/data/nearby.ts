/**
 * Genuinely adjacent location pages, for the "nearby areas" links.
 *
 * WHY THIS EXISTS
 * The location network was almost a star: every page received links from the
 * /locations/ hub and sent almost none onward. Measured on the built site, the
 * median page had 3 outbound location links and 61 pages had 2 or fewer
 * inbound, so authority arriving at the hub had nowhere to flow and the deeper
 * neighbourhood pages were effectively leaves.
 *
 * HOW IT IS BUILT
 * Generated, not hand-written. Each page's five closest same-city siblings are
 * computed from the coordinates the site already publishes in its
 * GeoCoordinates schema (src/data/location-geo.ts plus the inline `geo:` blocks
 * on each page) — so "nearby" is a measured fact, not an editorial guess. A
 * 12 km ceiling keeps the claim honest: the median linked neighbour is 2.3 km
 * away and the furthest is 11.8. Ten outlying towns have no sibling inside that
 * radius and correctly get no block at all rather than a misleading one.
 *
 * Keys are CANONICAL paths. Several locations answer on two routes
 * (/locations/morinville and /cleaning-services-morinville are one page), so
 * the component looks itself up through canonicalForPath and both routes hit
 * the same entry.
 *
 * Regenerate rather than edit by hand if the coordinate set changes.
 */
